"""
AERIS Interactive Engineering Dashboard Page (/dashboard).

Renders Plotly visualizations (single-signal and coordinated multi-signal panels)
generated by the backend REST API, complete with engineering limit overlays and hover inspection.
"""

from __future__ import annotations

from typing import Any

import dash_bootstrap_components as dbc
from dash import ALL, Input, Output, State, dcc, html, no_update
from dash.development.base_component import Component

from aeris.frontend.client import AerisApiClient, AerisApiError
from aeris.frontend.components.empty_state import render_empty_state
from aeris.frontend.components.epistemic_badge import render_epistemic_badge
from aeris.frontend.theme import CARD_STYLE, HEADER_STYLE, SUBTITLE_STYLE

AVAILABLE_SIGNALS = [
    ("indicated_airspeed", "Indicated Airspeed (IAS) [knots]"),
    ("pressure_altitude", "Pressure Altitude [ft]"),
    ("pitch_attitude", "Pitch Attitude [deg]"),
    ("roll_rate", "Roll Angular Rate (p) [deg/s]"),
    ("pitch_rate", "Pitch Angular Rate (q) [deg/s]"),
    ("dynamic_pressure", "Dynamic Pressure (qbar) [psf]"),
    ("mach_number", "Mach Number (M)"),
    ("angle_of_attack", "Angle of Attack (alpha) [deg]"),
    ("vertical_acceleration", "Normal Load Factor (Nz) [g]"),
]


def layout() -> Component:
    """Render the Interactive Engineering Dashboard page layout."""
    return dbc.Container(
        [
            dbc.Row(
                [
                    dbc.Col(
                        [
                            html.H3("Interactive Engineering Dashboard", style=HEADER_STYLE),
                            html.P(
                                "Multi-signal synchronized time-series panels, threshold "
                                "overlays, and flight test point inspection.",
                                style=SUBTITLE_STYLE,
                            ),
                        ],
                        md=12,
                    ),
                ]
            ),
            html.Div(id="dashboard-page-content"),
        ],
        fluid=True,
        className="py-4 px-4",
    )


def build_dashboard_plot(
    api_client: AerisApiClient,
    project_id: str,
    analysis_id: str,
    active_signals: list[str],
    active_layout: str,
    active_limits: bool,
    active_events: bool,
    active_dark: bool,
) -> Component:
    """Query backend API and construct the coordinated Plotly visualization card."""
    if not active_signals:
        return dbc.Card(
            dbc.CardBody(
                [
                    render_empty_state(
                        title="No Signals Selected",
                        description=(
                            "Select one or more flight telemetry signals above to "
                            "render the dashboard panel."
                        ),
                        icon_text="[ SELECT SIGNALS ]",
                    )
                ]
            ),
            style=CARD_STYLE,
        )

    try:
        plot_resp = api_client.get_multi_signal_plot(
            project_id=project_id,
            analysis_id=analysis_id,
            signal_ids=active_signals,
            layout_mode=active_layout,
            show_limits=active_limits,
            show_events=active_events,
            dark_mode=active_dark,
        )
        figure_dict = plot_resp.get("figure_json", {})
        return dbc.Card(
            dbc.CardBody(
                [
                    html.Div(
                        [
                            html.Span(
                                f"COORDINATED PANEL: {', '.join(active_signals)}",
                                className="fw-bold text-muted small",
                            ),
                            html.Span(
                                f"Layout: {active_layout}",
                                className="badge bg-secondary ms-2",
                            ),
                        ],
                        className="mb-2 pb-2 border-bottom d-flex align-items-center",
                    ),
                    dcc.Graph(
                        figure=figure_dict,
                        config={"responsive": True, "displaylogo": False},
                        style={"minHeight": "600px"},
                    ),
                ]
            ),
            style=CARD_STYLE,
        )
    except AerisApiError as err:
        return dbc.Card(
            dbc.CardBody(
                [
                    render_empty_state(
                        title="Signal Visualization Unavailable",
                        description=(
                            f"The backend could not generate the multi-signal panel: {err.message}"
                        ),
                        action_button=dbc.Button(
                            "Configure Parameter Mappings",
                            href="/datasets",
                            color="primary",
                            className="mt-2",
                        ),
                        icon_text="[ SIGNAL DATA MISSING ]",
                    )
                ]
            ),
            style=CARD_STYLE,
        )


def register_callbacks(app: Any, api_client: AerisApiClient) -> None:
    """Register all Dash callbacks for the Engineering Dashboard."""

    @app.callback(
        Output("dashboard-page-content", "children"),
        Input("session-store", "data"),
    )
    def render_dashboard(session_data: dict[str, Any] | None) -> Component:
        project_id = session_data.get("active_project_id") if session_data else None
        analysis_id = session_data.get("active_analysis_id") if session_data else None

        if not project_id:
            return render_empty_state(
                title="No Active Project Selected",
                description=(
                    "Select or create a flight test project on the Projects page "
                    "before viewing telemetry dashboards."
                ),
                action_button=dbc.Button("Go to Projects", href="/projects", color="primary"),
                icon_text="[ WORKSPACE REQUIRED ]",
            )

        if not analysis_id:
            return render_empty_state(
                title="No Completed Analysis Run Selected",
                description=(
                    "Execute an analytical pipeline on the Analysis page to generate "
                    "interactive Plotly visualizations."
                ),
                action_button=dbc.Button("Go to Analysis", href="/analysis", color="primary"),
                icon_text="[ NO ANALYSIS RUN ]",
            )

        # Dynamic signals selection from backend
        signal_options = [{"label": label, "value": sig_id} for sig_id, label in AVAILABLE_SIGNALS]
        active_signals = ["indicated_airspeed", "pressure_altitude"]

        try:
            signals_data = api_client.get_available_signals(project_id, analysis_id)
            fetched = signals_data.get("signals", [])
            if fetched:
                signal_options = [
                    {
                        "label": (
                            f"{item['label']} [{item['unit']}]"
                            if item.get("unit") and f"[{item['unit']}]" not in item["label"]
                            else item["label"]
                        ),
                        "value": item["signal_id"],
                    }
                    for item in fetched
                ]
            suggested = signals_data.get("default_signals", [])
            if suggested:
                active_signals = suggested
            elif fetched:
                active_signals = [fetched[0]["signal_id"]]
        except Exception:
            pass

        active_layout = "STACKED"
        active_limits = True
        active_events = True
        active_dark = False

        # Control Panel
        controls_card = dbc.Card(
            dbc.CardBody(
                [
                    dbc.Row(
                        [
                            dbc.Col(
                                [
                                    dbc.Label(
                                        "Active Analysis Run",
                                        className="fw-semibold small text-muted",
                                    ),
                                    html.Div(
                                        [
                                            html.Code(analysis_id, className="fw-bold me-2"),
                                            render_epistemic_badge("CALCULATED RESULT"),
                                        ],
                                        className="d-flex align-items-center mb-3",
                                    ),
                                ],
                                md=4,
                            ),
                            dbc.Col(
                                [
                                    dbc.Label(
                                        "Telemetry Parameters to Display",
                                        className="fw-semibold small",
                                    ),
                                    dcc.Dropdown(
                                        id="dashboard-signal-select",
                                        options=signal_options,
                                        value=active_signals,
                                        multi=True,
                                        placeholder="Select signals...",
                                        className="mb-3",
                                    ),
                                ],
                                md=8,
                            ),
                        ]
                    ),
                    dbc.Row(
                        [
                            dbc.Col(
                                [
                                    dbc.Label("Panel Layout Mode", className="fw-semibold small"),
                                    dbc.Select(
                                        id="dashboard-layout-mode-select",
                                        options=[
                                            {
                                                "label": "Stacked Subplots (Coordinated X-Axis)",
                                                "value": "STACKED",
                                            },
                                            {
                                                "label": "Single Overlay (Normalized)",
                                                "value": "OVERLAY",
                                            },
                                            {
                                                "label": "Unit-Grouped Subplots",
                                                "value": "UNIT_GROUPED",
                                            },
                                        ],
                                        value=active_layout,
                                        className="mb-3",
                                    ),
                                ],
                                md=4,
                            ),
                            dbc.Col(
                                [
                                    dbc.Label(
                                        "Visualization Overlays",
                                        className="fw-semibold small d-block",
                                    ),
                                    dbc.Checkbox(
                                        id="dashboard-show-limits-check",
                                        label="Show Envelope Limits",
                                        value=active_limits,
                                        className="d-inline-block me-3",
                                    ),
                                    dbc.Checkbox(
                                        id="dashboard-show-events-check",
                                        label="Show Test Events",
                                        value=active_events,
                                        className="d-inline-block me-3",
                                    ),
                                    dbc.Checkbox(
                                        id="dashboard-dark-mode-check",
                                        label="Dark Theme",
                                        value=active_dark,
                                        className="d-inline-block",
                                    ),
                                ],
                                md=5,
                            ),
                            dbc.Col(
                                [
                                    dbc.Button(
                                        "Update Visualization",
                                        id={"type": "update-dashboard-plot-btn", "index": "action"},
                                        color="primary",
                                        className="w-100 mt-4",
                                    ),
                                ],
                                md=3,
                            ),
                        ]
                    ),
                ]
            ),
            style=CARD_STYLE,
            className="mb-4",
        )

        initial_plot = build_dashboard_plot(
            api_client=api_client,
            project_id=project_id,
            analysis_id=analysis_id,
            active_signals=active_signals,
            active_layout=active_layout,
            active_limits=active_limits,
            active_events=active_events,
            active_dark=active_dark,
        )

        return html.Div(
            [
                controls_card,
                html.Div(id="dashboard-plot-container", children=initial_plot),
            ]
        )

    @app.callback(
        Output("dashboard-plot-container", "children"),
        Input({"type": "update-dashboard-plot-btn", "index": ALL}, "n_clicks"),
        [
            State("dashboard-signal-select", "value"),
            State("dashboard-layout-mode-select", "value"),
            State("dashboard-show-limits-check", "value"),
            State("dashboard-show-events-check", "value"),
            State("dashboard-dark-mode-check", "value"),
            State("session-store", "data"),
        ],
        prevent_initial_call=True,
    )
    def update_dashboard_plot(
        _clicks: Any,
        selected_signals: list[str] | None,
        layout_mode: str | None,
        show_limits: bool | None,
        show_events: bool | None,
        dark_mode: bool | None,
        session_data: dict[str, Any] | None,
    ) -> Any:
        if not _clicks or not any(c for c in _clicks if c):
            return no_update

        project_id = session_data.get("active_project_id") if session_data else None
        analysis_id = session_data.get("active_analysis_id") if session_data else None

        if not project_id or not analysis_id:
            return html.Div()

        active_signals = selected_signals if selected_signals is not None else []
        active_layout = layout_mode or "STACKED"
        active_limits = True if show_limits is None else bool(show_limits)
        active_events = True if show_events is None else bool(show_events)
        active_dark = False if dark_mode is None else bool(dark_mode)

        return build_dashboard_plot(
            api_client=api_client,
            project_id=project_id,
            analysis_id=analysis_id,
            active_signals=active_signals,
            active_layout=active_layout,
            active_limits=active_limits,
            active_events=active_events,
            active_dark=active_dark,
        )
