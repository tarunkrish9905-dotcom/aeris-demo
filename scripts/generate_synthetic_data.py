"""
Synthetic Flight-Test Dataset Generator for AERIS Test Fixtures.

DISCLAIMER:
All datasets generated by this module are purely SYNTHETIC test fixtures
designed exclusively for automated testing of ingestion, schema validation,
and data quality behavior. They do NOT represent any real aircraft, flight test,
or operational telemetry data. No aircraft-specific specifications or real-world
operational limits are modeled or implied.
"""

from __future__ import annotations

import argparse
import math
import pathlib
from datetime import UTC, datetime
from typing import Final

import numpy as np
import pandas as pd

# ---------------------------------------------------------------------------
# Constants & Schema Definition
# ---------------------------------------------------------------------------

STANDARD_COLUMNS: Final[list[str]] = [
    "timestamp",
    "altitude_ft",
    "airspeed_kts",
    "pitch_deg",
    "roll_deg",
    "engine_rpm",
]

DEFAULT_ROW_COUNT: Final[int] = 60
BASE_TIMESTAMP_ISO: Final[str] = "2026-10-06T10:00:00.000Z"


def get_default_output_dir() -> pathlib.Path:
    """Return the default output directory for generated CSV fixtures."""
    # scripts/ lives at <project_root>/scripts/ -> project root is parent
    project_root = pathlib.Path(__file__).resolve().parent.parent
    return project_root / "tests" / "fixtures" / "csv"


# ---------------------------------------------------------------------------
# Dataset Generators
# ---------------------------------------------------------------------------


def generate_clean_dataset(
    num_rows: int = DEFAULT_ROW_COUNT,
    start_time_iso: str = BASE_TIMESTAMP_ISO,
) -> pd.DataFrame:
    """Generate a clean synthetic flight-test telemetry dataset.

    Characteristics:
    - Exactly standard columns present
    - Strictly monotonic 1 Hz timestamps (ISO 8601 UTC)
    - Zero missing values
    - Zero duplicate timestamps
    - Continuous, smooth synthetic numeric series
    """
    base_dt = datetime.fromisoformat(start_time_iso.replace("Z", "+00:00"))

    timestamps: list[str] = []
    altitudes: list[float] = []
    airspeeds: list[float] = []
    pitches: list[float] = []
    rolls: list[float] = []
    rpms: list[float] = []

    for t in range(num_rows):
        # 1 Hz increment in UTC
        dt = datetime.fromtimestamp(base_dt.timestamp() + t, tz=UTC)
        timestamps.append(dt.strftime("%Y-%m-%dT%H:%M:%S.000Z"))

        # Deterministic synthetic smooth telemetry patterns
        # Cruise climb / steady level flight simulation
        altitudes.append(round(5000.0 + 15.0 * t + 8.0 * math.sin(t * 0.1), 2))
        airspeeds.append(round(135.0 + 3.0 * math.cos(t * 0.08), 2))
        pitches.append(round(2.5 + 0.6 * math.sin(t * 0.15), 2))
        rolls.append(round(0.0 + 1.2 * math.sin(t * 0.1), 2))
        rpms.append(round(2450.0 + 12.0 * math.cos(t * 0.05), 2))

    df = pd.DataFrame(
        {
            "timestamp": timestamps,
            "altitude_ft": altitudes,
            "airspeed_kts": airspeeds,
            "pitch_deg": pitches,
            "roll_deg": rolls,
            "engine_rpm": rpms,
        }
    )
    return df


def generate_missing_values_dataset(base_df: pd.DataFrame) -> pd.DataFrame:
    """Generate dataset with deliberate, traceable missing values (NaN).

    Injects missing values in specific parameters across selected rows
    while keeping the timestamp column intact and preserving sufficient
    valid data for testing graceful degradation.
    """
    df = base_df.copy()

    # Strategic omissions:
    # 1. Single missing value in altitude (row 5)
    df.loc[5, "altitude_ft"] = np.nan

    # 2. Consecutive missing values in roll (rows 12, 13)
    df.loc[12:13, "roll_deg"] = np.nan

    # 3. Multiple concurrent missing parameters (row 25)
    df.loc[25, "airspeed_kts"] = np.nan
    df.loc[25, "pitch_deg"] = np.nan

    # 4. Engine parameter gap (row 42)
    df.loc[42, "engine_rpm"] = np.nan

    return df


def generate_invalid_timestamps_dataset(base_df: pd.DataFrame) -> pd.DataFrame:
    """Generate dataset with deliberate unparseable timestamp entries.

    Injects non-ISO, malformed, and out-of-range timestamp strings at
    specific traceable rows while preserving valid numeric telemetry.
    """
    df = base_df.copy()

    # Controlled invalid timestamps
    df.loc[7, "timestamp"] = "INVALID_TIMESTAMP_STRING"
    df.loc[21, "timestamp"] = "2026-99-99T99:99:99.000Z"
    df.loc[38, "timestamp"] = "10/06/2026 25:70:00"
    df.loc[50, "timestamp"] = ""

    return df


def generate_duplicate_timestamps_dataset(base_df: pd.DataFrame) -> pd.DataFrame:
    """Generate dataset with deliberate duplicate timestamp entries.

    Repeats timestamps from adjacent rows to test duplicate timestamp
    detection and handling.
    """
    df = base_df.copy()

    # Duplicate row 10 timestamp onto row 11
    df.loc[11, "timestamp"] = df.loc[10, "timestamp"]

    # Duplicate row 32 timestamp onto rows 33 and 34 (cluster duplicate)
    df.loc[33, "timestamp"] = df.loc[32, "timestamp"]
    df.loc[34, "timestamp"] = df.loc[32, "timestamp"]

    return df


def generate_unordered_timestamps_dataset(base_df: pd.DataFrame) -> pd.DataFrame:
    """Generate dataset with deliberate out-of-order chronological entries.

    Swaps and transposes specific rows so sequential timestamp checks
    detect negative time deltas.
    """
    df = base_df.copy()

    # Swap row 14 and row 15
    row_14 = df.iloc[14].copy()
    row_15 = df.iloc[15].copy()
    df.iloc[14] = row_15
    df.iloc[15] = row_14

    # Move row 45 back to position 38 (displaced backwards jump)
    indices = list(range(len(df)))
    indices.remove(45)
    indices.insert(38, 45)
    df = df.iloc[indices].reset_index(drop=True)

    return df


def write_malformed_empty_file(target_file: pathlib.Path) -> None:
    """Create a completely empty (0-byte) file representing empty input."""
    target_file.parent.mkdir(parents=True, exist_ok=True)
    target_file.write_bytes(b"")


def generate_all_datasets(output_dir: pathlib.Path) -> dict[str, pathlib.Path]:
    """Generate and write all 6 synthetic test fixtures to output_dir."""
    output_dir.mkdir(parents=True, exist_ok=True)
    generated: dict[str, pathlib.Path] = {}

    # 1. clean_flight.csv
    clean_df = generate_clean_dataset()
    clean_path = output_dir / "clean_flight.csv"
    clean_df.to_csv(clean_path, index=False)
    generated["clean_flight"] = clean_path

    # 2. missing_values.csv
    missing_df = generate_missing_values_dataset(clean_df)
    missing_path = output_dir / "missing_values.csv"
    missing_df.to_csv(missing_path, index=False)
    generated["missing_values"] = missing_path

    # 3. invalid_timestamps.csv
    invalid_ts_df = generate_invalid_timestamps_dataset(clean_df)
    invalid_ts_path = output_dir / "invalid_timestamps.csv"
    invalid_ts_df.to_csv(invalid_ts_path, index=False)
    generated["invalid_timestamps"] = invalid_ts_path

    # 4. duplicate_timestamps.csv
    dup_ts_df = generate_duplicate_timestamps_dataset(clean_df)
    dup_ts_path = output_dir / "duplicate_timestamps.csv"
    dup_ts_df.to_csv(dup_ts_path, index=False)
    generated["duplicate_timestamps"] = dup_ts_path

    # 5. unordered_timestamps.csv
    unordered_ts_df = generate_unordered_timestamps_dataset(clean_df)
    unordered_ts_path = output_dir / "unordered_timestamps.csv"
    unordered_ts_df.to_csv(unordered_ts_path, index=False)
    generated["unordered_timestamps"] = unordered_ts_path

    # 6. malformed_empty.csv
    empty_path = output_dir / "malformed_empty.csv"
    write_malformed_empty_file(empty_path)
    generated["malformed_empty"] = empty_path

    return generated


def main() -> None:
    """CLI entrypoint for generating synthetic test datasets."""
    parser = argparse.ArgumentParser(
        description="Generate synthetic flight-test CSV datasets for AERIS test fixtures."
    )
    parser.add_argument(
        "--output-dir",
        type=pathlib.Path,
        default=get_default_output_dir(),
        help="Directory where CSV fixture files will be saved.",
    )
    args = parser.parse_args()

    output_dir: pathlib.Path = args.output_dir
    print(f"Generating synthetic datasets into: {output_dir}")
    generated = generate_all_datasets(output_dir)

    for name, path in generated.items():
        size = path.stat().st_size
        print(f"  [OK] {name:<22} -> {path.name} ({size} bytes)")
    print("Generation complete.")


if __name__ == "__main__":
    main()
